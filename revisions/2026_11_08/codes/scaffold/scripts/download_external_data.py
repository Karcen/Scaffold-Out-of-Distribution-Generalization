#!/usr/bin/env python3
"""Download the six matched TDC tables from Harvard Dataverse.

The IDs are from PyTDC metadata v1.1.15.  Files are small raw tables and are
kept unchanged under ``data/external``; provenance hashes are generated by the
diagnostic script.
"""

from __future__ import annotations

from pathlib import Path
from urllib.request import urlopen


FILES = {
    "BBB_Martins.tab": 4259566,
    "HIA_Hou.tab": 4259591,
    "CYP2D6_Veith.tab": 4259580,
    "PPBR_AZ.tab": 6413140,
    "Solubility_AqSolDB.tab": 4259610,
    "DILI.tab": 4259585,
}


def main() -> None:
    root = Path("data/external")
    root.mkdir(parents=True, exist_ok=True)
    for filename, file_id in FILES.items():
        destination = root / filename
        if destination.exists() and destination.stat().st_size > 0:
            print(f"present {destination}")
            continue
        url = f"https://dataverse.harvard.edu/api/access/datafile/{file_id}"
        print(f"download {url} -> {destination}")
        with urlopen(url, timeout=120) as response:
            destination.write_bytes(response.read())


if __name__ == "__main__":
    main()

